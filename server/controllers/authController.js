// @desc    Update user profile & password
// @route   PUT /api/auth/profile
// @access  Private
exports.updateProfile = async (req, res, next) => {
  try {
    const { name, bio, currentPassword, newPassword } = req.body;
    const user = await User.findById(req.user.id).select('+password');

    if (name) user.name = name;
    if (bio !== undefined) user.bio = bio;

    if (newPassword) {
      if (!currentPassword) {
        return res.status(400).json({ success: false, message: 'Current password is required to change password' });
      }
      const isMatch = await bcrypt.compare(currentPassword, user.password);
      if (!isMatch) {
        return res.status(400).json({ success: false, message: 'Current password is incorrect' });
      }
      const salt = await bcrypt.genSalt(10);
      user.password = await bcrypt.hash(newPassword, salt);
    }

    await user.save();

    res.json({
      success: true,
      user: {
        id: user._id,
        name: user.name,
        email: user.email,
        avatar: user.avatar,
        role: user.role,
        bio: user.bio,
        createdAt: user.createdAt,
      },
      message: 'Profile updated successfully',
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Forgot password flow simulation
// @route   POST /api/auth/forgot-password
// @access  Public
exports.forgotPassword = async (req, res, next) => {
  try {
    const { email } = req.body;
    const user = await User.findOne({ email });

    if (!user) {
      // Return 200 to prevent user enumeration
      return res.json({
        success: true,
        message: 'If an account exists with that email, reset instructions have been sent.',
      });
    }

    res.json({
      success: true,
      message: 'Password reset simulation: Instructions sent to email. Demo password reset allowed via profile settings or re-registration.',
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Search users for adding to project
// @route   GET /api/auth/users
// @access  Private
exports.searchUsers = async (req, res, next) => {
  try {
    const { q } = req.query;
    const query = q
      ? {
          $or: [
            { name: { $regex: q, $options: 'i' } },
            { email: { $regex: q, $options: 'i' } },
          ],
        }
      : {};

    const users = await User.find(query).select('name email avatar').limit(10);
    res.json({ success: true, users });
  } catch (error) {
    next(error);
  }
};
